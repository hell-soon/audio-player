/**
 * «Обложки как пластинки» (Оформление): у крупной обложки (карточка «Сейчас играет», полноэкранный режим)
 * две стороны — спереди обложка, сзади виниловая пластинка; касание/клик переворачивает.
 * В cookie — чтобы сервер сразу отрисовал как надо. Значение — boolean: useCookie сам разбирает
 * содержимое (строка '1' стала бы числом 1, и сравнение со строкой не срабатывало).
 */
export function useVinylCovers() {
  return useCookie<boolean>('vinyl', { default: () => false, maxAge: 60 * 60 * 24 * 365, sameSite: 'lax' })
}
